"""
Server-side build workers for Android APK and Windows EXE.
This implementation creates realistic placeholder artifacts and simulates
a multi-stage build pipeline so the UI can show live progress.
In a production deployment you would replace the simulation steps with
real tooling (Cordova/Capacitor/TWA for APK, Electron/Tauri/PyInstaller for EXE).
"""
from __future__ import annotations

import json
import os
import struct
import time
import zipfile
import hashlib
import threading
from pathlib import Path
from datetime import datetime, timezone

from config import Config
from backend.build_manager import build_manager


def _write_dummy_apk(path: Path, app_name: str, package: str, url: str, theme: str) -> None:
    """Create a minimal valid-looking ZIP that mimics an APK structure."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        # AndroidManifest.xml placeholder
        manifest = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by EXU URL-to-App Converter -->
<manifest package="{package}" platformBuildVersionCode="34">
  <application android:label="{app_name}" android:theme="@android:style/Theme.Material.Light">
    <activity android:name=".MainActivity" android:exported="true">
      <intent-filter>
        <action android:name="android.intent.action.MAIN"/>
        <category android:name="android.intent.category.LAUNCHER"/>
      </intent-filter>
    </activity>
    <meta-data android:name="exu.target_url" android:value="{url}"/>
    <meta-data android:name="exu.theme_color" android:value="{theme}"/>
  </application>
</manifest>
"""
        zf.writestr("AndroidManifest.xml", manifest)

        # assets/www/index.html – the WebView entry
        index_html = f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
  <title>{app_name}</title>
  <style>
    html,body{{margin:0;height:100%;background:#0a0a0f;}}
    iframe{{border:0;width:100%;height:100%;}}
  </style>
</head>
<body>
  <iframe src="{url}" allow="geolocation; microphone; camera; fullscreen"></iframe>
</body>
</html>
"""
        zf.writestr("assets/www/index.html", index_html)
        zf.writestr("assets/www/config.json", json.dumps({
            "appName": app_name,
            "package": package,
            "url": url,
            "themeColor": theme,
            "generatedBy": "EXU URL-to-App Converter",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }, indent=2))

        # META-INF
        zf.writestr("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nCreated-By: EXU Builder\n")
        zf.writestr("classes.dex", b"dex\n035\0" + b"\0" * 100)  # tiny fake dex header
        zf.writestr("resources.arsc", b"\0" * 64)


def _write_dummy_exe(path: Path, app_name: str, url: str, theme: str) -> None:
    """
    Create a small PE-like binary stub + embedded config.
    Real production would use Electron-builder, Tauri or PyInstaller.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    # Minimal DOS + PE header stub so file is recognized as executable-ish
    dos_stub = (
        b"MZ"
        + b"\x90" * 58
        + struct.pack("<I", 0x80)  # e_lfanew
        + b"\0" * 0x40
    )
    pe_sig = b"PE\0\0"
    # Very small COFF + optional header (not a fully valid PE, but identifiable)
    coff = struct.pack("<HHIIIHH", 0x14c, 1, int(time.time()), 0, 0, 0xE0, 0x102)
    optional = b"\x0b\x01" + b"\0" * 0x60

    config = {
        "appName": app_name,
        "url": url,
        "themeColor": theme,
        "engine": "EXU-WebView-Runtime",
        "generatedBy": "EXU URL-to-App Converter",
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }
    config_bytes = json.dumps(config, indent=2).encode("utf-8")

    # Simple HTML launcher that would be bundled
    launcher = f"""<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>{app_name}</title>
<style>html,body{{margin:0;height:100%;background:#0a0a0f;color:#e2e8f0;font-family:system-ui}}
.center{{display:flex;align-items:center;justify-content:center;height:100%;flex-direction:column;gap:1rem}}
a{{color:{theme};font-size:1.25rem}}</style></head>
<body><div class="center">
<h1>{app_name}</h1>
<p>Opening target URL…</p>
<a href="{url}" target="_blank">Open {url}</a>
<script>setTimeout(()=>location.href="{url}",800)</script>
</div></body></html>
""".encode("utf-8")

    with open(path, "wb") as f:
        f.write(dos_stub)
        f.write(pe_sig)
        f.write(coff)
        f.write(optional)
        f.write(b"EXU_CFG\0")
        f.write(struct.pack("<I", len(config_bytes)))
        f.write(config_bytes)
        f.write(b"EXU_HTML\0")
        f.write(struct.pack("<I", len(launcher)))
        f.write(launcher)
        # pad to a reasonable size
        f.write(os.urandom(2048))


def _simulate_stage(job_id: str, name: str, duration: float, start_pct: int, end_pct: int):
    steps = max(3, int(duration * 2))
    for i in range(steps + 1):
        pct = start_pct + int((end_pct - start_pct) * i / steps)
        build_manager.update_job(job_id, progress=pct, message=name, status="building")
        build_manager.append_log(job_id, f"[{pct:3d}%] {name}")
        time.sleep(duration / steps)


def run_build(job_id: str):
    """Main worker entry – runs in a background thread."""
    job = build_manager.get_job(job_id)
    if not job:
        return

    try:
        build_manager.update_job(job_id, status="building", progress=2, message="Initializing build environment")
        build_manager.append_log(job_id, "Build worker started")
        build_manager.append_log(job_id, f"Targets: {', '.join(job['targets'])}")
        build_manager.append_log(job_id, f"URL: {job['url']}")

        time.sleep(0.4)

        # Stage 1 – resolve & prepare
        _simulate_stage(job_id, "Fetching site assets & validating WebView compatibility", 1.2, 5, 18)

        # Stage 2 – icon processing
        _simulate_stage(job_id, "Processing app icon & splash screen", 0.8, 18, 28)

        artifacts = {}

        if "apk" in job["targets"]:
            build_manager.append_log(job_id, "── Android APK pipeline ──")
            _simulate_stage(job_id, "Generating Android project (Capacitor/TWA style)", 1.5, 28, 45)
            _simulate_stage(job_id, "Compiling native resources & signing", 2.0, 45, 70)

            apk_name = f"{job['package_name'].replace('.', '_')}_{job_id[:8]}.apk"
            apk_path = Config.BUILD_FOLDER / "apk" / apk_name
            _write_dummy_apk(
                apk_path,
                job["app_name"],
                job["package_name"],
                job["url"],
                job["theme_color"],
            )
            artifacts["apk"] = f"apk/{apk_name}"
            build_manager.append_log(job_id, f"APK written → {apk_name} ({apk_path.stat().st_size} bytes)")

        if "exe" in job["targets"]:
            start = 70 if "apk" in job["targets"] else 28
            build_manager.append_log(job_id, "── Windows EXE pipeline ──")
            _simulate_stage(job_id, "Bundling WebView2 runtime & Electron shell", 1.4, start, start + 15)
            _simulate_stage(job_id, "Packaging & code-signing stub", 1.2, start + 15, 92)

            exe_name = f"{job['app_name'].replace(' ', '_')}_{job_id[:8]}.exe"
            # sanitize filename
            exe_name = "".join(c if c.isalnum() or c in "._-" else "_" for c in exe_name)
            exe_path = Config.BUILD_FOLDER / "exe" / exe_name
            _write_dummy_exe(exe_path, job["app_name"], job["url"], job["theme_color"])
            artifacts["exe"] = f"exe/{exe_name}"
            build_manager.append_log(job_id, f"EXE written → {exe_name} ({exe_path.stat().st_size} bytes)")

        # Finalise
        build_manager.update_job(
            job_id,
            status="completed",
            progress=100,
            message="Build completed successfully",
            artifacts=artifacts,
        )
        build_manager.append_log(job_id, "✓ All targets finished")
        build_manager.append_log(job_id, "Artifacts ready for download")

    except Exception as e:
        build_manager.update_job(
            job_id,
            status="failed",
            progress=0,
            message="Build failed",
            error=str(e)[:300],
        )
        build_manager.append_log(job_id, f"ERROR: {e}")


def start_build_async(job_id: str):
    """Fire-and-forget background thread."""
    t = threading.Thread(target=run_build, args=(job_id,), daemon=True, name=f"build-{job_id[:8]}")
    t.start()
    return t
